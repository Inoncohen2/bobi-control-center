def _cap(
    cap_id: str,
    name: str,
    description: str,
    icon: str,
    group: str,
    *,
    enabled: bool = True,
    state: HealthState = HealthState.ONLINE,
    state_label: str = "פעיל",
    warning: str | None = None,
    settings: list[CapabilitySetting] | None = None,
    devices: list[str] | None = None,
    last_used_hours: int | None = 2,
    notes: list[str] | None = None,
) -> Capability:
    return Capability(
        id=cap_id,
        name=name,
        description=description,
        icon=icon,
        group=group,
        enabled=enabled,
        state=state,
        state_label=state_label,
        warning=warning,
        settings=settings or [],
        related_device_ids=devices or [],
        last_used=hours_ago(last_used_hours) if last_used_hours is not None else None,
        advanced=Advanced(notes=notes or []),
    )


